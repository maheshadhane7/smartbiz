/**
 * Generates 100+ realistic invoices across past 90 days
 */
export function generateSeedInvoices(products: Product[], customersRaw: Partial<Customer>[]): {
  invoices: Invoice[];
  customers: Customer[];
  payments: PaymentRecord[];
  stockMovements: StockMovement[];
  auditLogs: AuditLog[];
} {
  const invoices: Invoice[] = [];
  const payments: PaymentRecord[] = [];
  const stockMovements: StockMovement[] = [];
  const auditLogs: AuditLog[] = [];

  const paymentModes: Invoice['paymentMode'][] = ['UPI', 'CASH', 'CARD', 'BANK_TRANSFER', 'CREDIT'];
  const today = new Date();

  // Create full customer records with intelligence
  const customers: Customer[] = customersRaw.map((raw, idx) => {
    const cust: Customer = {
      id: raw.id || `cust_${idx + 1}`,
      name: raw.name || `Customer ${idx + 1}`,
      companyName: raw.companyName,
      phone: raw.phone || `+91 98200 ${idx.toString().padStart(5, '0')}`,
      email: raw.email || `cust${idx + 1}@example.com`,
      gstin: raw.gstin || '',
      state: raw.state || 'Maharashtra',
      stateCode: raw.stateCode || '27',
      address: raw.address || 'Mumbai, Maharashtra',
      type: raw.type || 'RETAIL',
      creditLimit: raw.creditLimit || 50000,
      outstandingBalance: raw.outstandingBalance || 0,
      totalPurchases: raw.totalPurchases || 0,
      totalOrders: raw.totalOrders || 0,
      lastPurchaseDate: raw.lastPurchaseDate,
      intelligence: {
        rfmScore: 75,
        recencyDays: 5,
        frequencyOrders: raw.totalOrders || 10,
        monetaryTotal: raw.totalPurchases || 50000,
        paymentDelayAvgDays: raw.outstandingBalance && raw.outstandingBalance > 30000 ? 18 : 2,
        riskCategory: raw.outstandingBalance && raw.outstandingBalance > 30000 ? 'HIGH_PAYMENT_RISK' : 'REGULAR',
        churnProbability: 15,
        delayProbability: raw.outstandingBalance && raw.outstandingBalance > 30000 ? 75 : 8,
        recommendation: 'Standard retail account.',
        insights: [],
      },
      createdAt: '2026-01-01T00:00:00Z',
    };

    return cust;
  });

  let invSequence = 101;

  for (let i = 0; i < 110; i++) {
    const daysAgo = Math.floor(Math.random() * 85);
    const invDate = new Date(today);
    invDate.setDate(invDate.getDate() - daysAgo);

    const custIndex = i % customers.length;
    const customer = customers[custIndex];
    const isInterState = customer.stateCode !== '27';

    // Pick 1 to 4 random products
    const itemCount = 1 + Math.floor(Math.random() * 3);
    const selectedItems: Invoice['items'] = [];

    let subtotal = 0;
    let discountTotal = 0;
    let taxableTotal = 0;
    let cgstTotal = 0;
    let sgstTotal = 0;
    let igstTotal = 0;

    for (let k = 0; k < itemCount; k++) {
      const prod = products[(i + k * 3) % products.length];
      const qty = 1 + Math.floor(Math.random() * 5);
      const discountPercent = (i === 15) ? 30 : (Math.random() > 0.8 ? 5 : 0); // Seed an anomaly at i=15

      const taxRes = calculateItemTax(prod.sellingPrice, qty, discountPercent, prod.gstRate, isInterState);

      selectedItems.push({
        productId: prod.id,
        productName: prod.name,
        sku: prod.sku,
        hsnCode: prod.hsnCode,
        quantity: qty,
        unit: prod.unit,
        costPrice: prod.costPrice,
        unitPrice: prod.sellingPrice,
        discountPercent,
        discountAmount: (prod.sellingPrice * qty * discountPercent) / 100,
        taxableAmount: taxRes.taxableAmount,
        gstRate: prod.gstRate,
        cgstRate: taxRes.cgstRate,
        cgstAmount: taxRes.cgstAmount,
        sgstRate: taxRes.sgstRate,
        sgstAmount: taxRes.sgstAmount,
        igstRate: taxRes.igstRate,
        igstAmount: taxRes.igstAmount,
        totalAmount: taxRes.totalAmount,
      });

      subtotal += prod.sellingPrice * qty;
      discountTotal += (prod.sellingPrice * qty * discountPercent) / 100;
      taxableTotal += taxRes.taxableAmount;
      cgstTotal += taxRes.cgstAmount;
      sgstTotal += taxRes.sgstAmount;
      igstTotal += taxRes.igstAmount;
    }

    const totalTax = cgstTotal + sgstTotal + igstTotal;
    const rawGrandTotal = taxableTotal + totalTax;
    const grandTotal = Math.round(rawGrandTotal);
    const roundOff = Number((grandTotal - rawGrandTotal).toFixed(2));

    const dueDate = new Date(invDate);
    dueDate.setDate(dueDate.getDate() + 15); // 15 days credit

    // Determine status & payment
    let status: Invoice['status'] = 'PAID';
    let paidAmount = grandTotal;
    let balanceAmount = 0;
    const paymentMode = paymentModes[i % paymentModes.length];

    if (customer.outstandingBalance > 0 && (i % 3 === 0)) {
      if (daysAgo > 15) {
        status = 'OVERDUE';
        paidAmount = Math.random() > 0.5 ? Math.floor(grandTotal * 0.4) : 0;
        balanceAmount = grandTotal - paidAmount;
      } else {
        status = 'UNPAID';
        paidAmount = 0;
        balanceAmount = grandTotal;
      }
    }

    const invoiceId = `inv_${invSequence}`;
    const invoiceNumber = `INV-2026-00${invSequence}`;

    const invoice: Invoice = {
      id: invoiceId,
      invoiceNumber,
      customerId: customer.id,
      customerName: customer.name,
      customerPhone: customer.phone,
      customerGstin: customer.gstin,
      customerState: customer.state,
      customerStateCode: customer.stateCode,
      isInterState,
      items: selectedItems,
      subtotal: Number(subtotal.toFixed(2)),
      discountTotal: Number(discountTotal.toFixed(2)),
      taxableTotal: Number(taxableTotal.toFixed(2)),
      cgstTotal: Number(cgstTotal.toFixed(2)),
      sgstTotal: Number(sgstTotal.toFixed(2)),
      igstTotal: Number(igstTotal.toFixed(2)),
      totalTax: Number(totalTax.toFixed(2)),
      roundOff,
      grandTotal,
      paidAmount,
      balanceAmount,
      paymentMode,
      status,
      dueDate: dueDate.toISOString().slice(0, 10),
      createdAt: invDate.toISOString(),
      createdBy: 'usr_cashier',
      cashierName: 'Amit Verma',
    };

    invoices.push(invoice);

    if (paidAmount > 0) {
      payments.push({
        id: `pay_${invSequence}`,
        receiptNumber: `REC-2026-00${invSequence}`,
        invoiceId,
        invoiceNumber,
        customerId: customer.id,
        customerName: customer.name,
        amount: paidAmount,
        paymentMode,
        transactionRef: paymentMode === 'UPI' ? `UPI${Math.floor(100000000000 + Math.random() * 900000000000)}` : undefined,
        status: 'SUCCESS',
        recordedBy: 'Amit Verma (Cashier)',
        createdAt: invDate.toISOString(),
      });
    }

    invSequence++;
  }

  // Recalculate customer intelligence with generated invoices
  for (const cust of customers) {
    cust.intelligence = computeCustomerIntelligence(cust, invoices);
  }

  // Seed audit logs
  auditLogs.push(
    {
      id: 'log_1',
      userId: 'usr_admin',
      userName: 'Rajesh Sharma',
      userRole: 'admin',
      action: 'SYSTEM_STARTUP',
      module: 'System',
      details: 'SmartBiz ERP platform initialized with realistic Indian business seed dataset.',
      timestamp: '2026-08-15T08:00:00Z',
    },
    {
      id: 'log_2',
      userId: 'usr_cashier',
      userName: 'Amit Verma',
      userRole: 'cashier',
      action: 'INVOICE_CREATE',
      module: 'Billing',
      details: 'Generated POS Invoice INV-2026-00195 for Patel Supermarket (Grand Total: ₹4,850).',
      timestamp: '2026-08-15T11:20:00Z',
    },
    {
      id: 'log_3',
      userId: 'usr_accountant',
      userName: 'Sunita Patel',
      userRole: 'accountant',
      action: 'PAYMENT_RECORD',
      module: 'Payments',
      details: 'Recorded UPI payment receipt REC-2026-00192 of ₹12,500 from Krishna Traders.',
      timestamp: '2026-08-15T12:05:00Z',
    },
    {
      id: 'log_4',
      userId: 'usr_manager',
      userName: 'Priya Deshmukh',
      userRole: 'manager',
      action: 'AI_VOICE_CALL',
      module: 'Call Center',
      details: 'Triggered AI Voice Reminder call to Sharma Electronics for overdue amount ₹34,500.',
      timestamp: '2026-08-15T14:30:00Z',
    }
  );

  return { invoices, customers, payments, stockMovements, auditLogs };
}
